    def _generate_evaporation(self, parameters: Dict[str, Any]) -> str:
        """Generate evaporation section."""
        climate = parameters['climate']
        
        content = ["[EVAPORATION]"]
        content.append(";;Data Source    Parameters")
        
        if climate['evap_method'] == 'Constant':
            content.append(f"CONSTANT         {climate['evap_constant']:.3f}")
        elif climate['evap_method'] == 'Monthly':
            monthly_values = ' '.join([f"{val:.3f}" for val in climate['monthly_evap']])
            content.append(f"MONTHLY          {monthly_values}")
        elif climate['evap_method'] == 'Time Series':
            content.append("TIMESERIES       EvapSeries")
        
        content.append(f"RECOVERY         CONSTANT {climate['recovery_factor']:.2f}")
        content.append("DRY_ONLY         NO")
        
        return '\n'.join(content)
    
